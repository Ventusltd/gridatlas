/* Surgical no-layout derivative from immutable V9.191 SLD carrier.
 * Exact transformations protect the complete Grid Engine from truncation.
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
export const sourcePath='atlas/cartridges/202611161720-sld-sandbox-v9-8.js';
export const outputPath='atlas/modules/202611222130-sld-without-layout.js';
export const retireLayout = function retireLayout(source){
  function exact(a,b,description){
    const n=source.split(a).length-1;
    if(n!==1)throw Error(description+': expected one source anchor, got '+n);
    source=source.replace(a,b);
  }
  exact('        + `<button class="neon-layout" type="button">Lay out a scheme here &#9656;</button>`\n',
        '', 'layout card entry');
  exact('  function renderSldPanel() {\n',
        '  function renderSldPanel() {\n    return; // retired: layout panel never mounted\n',
        'layout panel guard');
  exact('  function openSldAt(map, gridNode, name, voltage) {\n',
        '  function openSldAt(map, gridNode, name, voltage) {\n    return false; // retired: no substation-triggered layout\n',
        'direct substation layout entry');
  exact('  function openSldFromProject(map, selection) {\n',
        '  function openSldFromProject(map, selection) {\n    return false; // retired: no project-triggered layout\n',
        'project layout entry');
  const start='  function installSld(map) {\n';
  const end='\n  }\n})();';
  const i=source.indexOf(start),j=i<0?-1:source.indexOf(end,i);
  if(i<0||j<0||source.indexOf(start,i+1)>=0)throw Error('installSld boundaries not unique');
  const removed=source.slice(i,j+5);
  for(const required of ['installSldStyles();','ensureSldLayers(map);','attachSldDragging(map);','openSldAt(map, at, properties.name','keepLayersInFullscreen();','armCorridorGestures(map);'])if(!removed.includes(required))throw Error('installSld evidence drift: '+required);
  const kept='  function installSld(map) {\n'
    +'    // Preserve fullscreen layers and corridors, not Layout Sandbox UI.\n'
    +'    try { keepLayersInFullscreen(); }\n'
    +"    catch (error) { link.failures.push('fullscreen: ' + String(error?.message || error)); }\n"
    +'    try { armCorridorGestures(map); }\n'
    +"    catch (error) { link.failures.push('corridor sheet: ' + String(error?.message || error)); }\n"
    +'  }';
  source=source.slice(0,i)+kept+source.slice(j+5);
  return source;
};
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const expected=retireLayout(fs.readFileSync(path.join(root,sourcePath),'utf8'));
 const file=path.join(root,outputPath);
 if(process.argv.includes('--check')){
   if(fs.readFileSync(file,'utf8')!==expected)throw Error('layout retirement generated bytes differ');
   console.log('PASS deterministic GridAtlas Layout Sandbox retirement: '+Buffer.byteLength(expected)+' bytes');
 }else{
   fs.writeFileSync(file,expected);
   console.log('wrote '+outputPath);
 }
}
