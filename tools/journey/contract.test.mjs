import assert from 'node:assert/strict';
import fs from 'node:fs';
import {createHash} from 'node:crypto';
import {planJourney} from './vendor/65d48a851fc2ac74b13f939a0184e11298e7e5bd/edge-cover-journey.js';
const read = p => JSON.parse(fs.readFileSync(new URL(p, import.meta.url)));
const fixture = read('./fixtures/synthetic-branch.v1.json'), pair = read('./fixtures/reviewed-pair.v1.json');
const clone = x => JSON.parse(JSON.stringify(x));
const make = (f, chosenNode) => planJourney({sourceBytes: f.networkText, ledger: f.ledger, query: {seed: {chosenNode}, bounds: {maxNodes: 25, maxEdges: 30, maxMoves: 60, maxGeometryBytes: 16000}}});
const p = await make(fixture, 'A1');
assert.equal(p.status, 'complete'); assert.equal(p.edgeCatalog.length, 4); assert.equal(p.steps.length, 8);
assert.ok(p.steps.some(s => s.traversal === 'backtrack'));
assert.ok(p.edgeCatalog.some(e => e.geometryStatus === 'verified_circuit_and_polyline'));
assert.equal(p.edgeCatalog.filter(e => e.schematic).length, 2);
assert.equal(p.edgeCatalog.filter(e => !e.coordinates).length, 1);
assert.equal(p.physicalUnits, null); assert.equal(p.planSha256, (await make(fixture, 'A1')).planSha256);
assert.equal((await make(fixture, '')).refusal, 'chosen_node_required');
assert.equal((await make(fixture, 'nearest')).refusal, 'seed_not_in_source');
const blocked = clone(fixture); blocked.ledger.nodes[0].rights = {status: 'blocked'};
assert.equal((await make(blocked, 'A1')).refusal, 'seed_rights_withheld');
const edgeBlocked = clone(fixture); for (const e of edgeBlocked.ledger.edges) e.rights = {status: 'blocked'};
assert.equal((await make(edgeBlocked, 'A1')).steps.length, 0);
const emptyLedger = clone(fixture); emptyLedger.ledger.nodes = []; emptyLedger.ledger.edges = [];
assert.equal((await make(emptyLedger, 'A1')).refusal, 'seed_identity_unreviewed');
const unsupported = clone(fixture); unsupported.ledger.edges[0].geometryStatus = 'invented';
await assert.rejects(make(unsupported, 'A1'), /unknown geometry evidence/);
const digestMismatch = clone(fixture); digestMismatch.networkText += ' ';
await assert.rejects(make(digestMismatch, 'A1'), /digest does not match/);
assert.equal((await make(pair, 'A1')).eligibleEdges, 1);
assert.equal(createHash('sha256').update(fs.readFileSync(new URL('./fixtures/reviewed-pair.v1.json', import.meta.url))).digest('hex'), '174ac6824c5a8fa5d161d6529840211d7d94472e2b2a172abdc25643b0230087');
console.log('Journey UI input contract: canonical shared fixture, deterministic branch/backtrack, polyline/schematic/unlocated, no-seed/nearest/rights/identity/geometry/digest refusals PASS');
