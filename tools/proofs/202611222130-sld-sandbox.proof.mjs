import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import vm from 'node:vm';
import {retireLayout,sourcePath,outputPath} from '../sld/retire-gridatlas-layout.mjs';
const root=path.resolve(import.meta.dirname,'../..');
const read=x=>fs.readFileSync(path.join(root,x),'utf8');
const manifest=JSON.parse(read('atlas/manifests/202611222130-composition.json'));
const preview=JSON.parse(read('atlas/v/202611222130/current.json'));
const live=JSON.parse(read('atlas/current.json'));
assert.equal(live.generation,'202611222000','do not publish from the candidate branch');
assert.equal(manifest.generation,'202611222130');
assert.equal(manifest.previous_generation,live.generation);
assert.equal(manifest.acceptance?.full_application_copies_created,0);
assert.equal(manifest.composition_manifest,'./manifests/202611222130-composition.json');
for(const key of ['parent_generation','version','cut_at_utc','note','acceptance','candidate_status'])delete manifest[key];
const canonical=JSON.stringify(manifest,null,1)+'\n';
const expectedPreview=canonical.replace(/": "(\.\/|\.\.\/)/g,'": "../../');
assert.equal(read('atlas/v/202611222130/current.json'),expectedPreview,'preview must be the exact live pointer re-rooted');
const sld=manifest.cartridges.find(c=>c.id==='sld-sandbox');
assert.equal(sld.generation,'202611222130');
assert.equal(sld.path,'./modules/202611222130-sld-without-layout.js');
const original=read(sourcePath),derived=read(outputPath);
assert.equal(derived,retireLayout(original),'exact minimal layout-only change');
assert.ok(Buffer.byteLength(derived)>445000,'carrier must not be truncated');
assert.equal(crypto.createHash('sha256').update(derived).digest('hex'),sld.sha256);
assert.equal(Buffer.byteLength(derived),sld.bytes);
new vm.Script(derived);
assert.ok(!derived.includes('        + `<button class="neon-layout"'));
assert.ok(derived.includes("return false; // retired: no substation-triggered layout"));
assert.ok(derived.includes("return false; // retired: no project-triggered layout"));
assert.ok(derived.includes('function enableSubstationLayer()'));
assert.ok(derived.includes('window.__GRIDATLAS_NEON_LINKS__'));
assert.ok(derived.includes('keepLayersInFullscreen();'));
assert.ok(derived.includes('armCorridorGestures(map);'));
assert.deepEqual(preview.cartridge_order,manifest.cartridge_order);
console.log('PASS release V9.195: no SLD UI, untouched source, full Grid Engine and release/preview byte parity');
