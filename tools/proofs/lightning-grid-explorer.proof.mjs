import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {resolve,dirname} from 'node:path';
import {spawnSync} from 'node:child_process';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'../../');
const page='atlas/labs/lightning-grid/index.html';
const app='atlas/labs/lightning-grid/app.mjs';
const html=readFileSync(resolve(root,page),'utf8');
const js=readFileSync(resolve(root,app),'utf8');
const live=JSON.parse(readFileSync(resolve(root,'atlas/current.json'),'utf8'));
let count=0;
const check=(condition,msg)=>{assert.ok(condition,msg);count++};
check(live.generation==='202609241334','Original live generation must be untouched');
check(html.includes('src="./app.mjs"'),'Lab uses separate JS sidecar');
check(html.includes('id="scenario" disabled'),'Scenario disabled until real selection');
check(html.includes('id="flash-map"'),'Separate spatial map is present');
check(html.includes('id="fit-flashes" disabled'),'Map never auto-fits without explicit action');
check(html.includes('id="fit-selection" disabled'),'User has an explicit selected-flash fit control');
check(html.includes('maplibre-gl@3.6.2'),'Uses the same MapLibre version as original GridAtlas');
const mapCode=readFileSync(resolve(root,'atlas/labs/lightning-grid/map-view.mjs'),'utf8');
check(mapCode.includes("'circle-radius':22"),'44 CSS px hit area uses a real 22 px hit circle');
check(mapCode.includes("'optical-flash-tap'"),'Optical point click layer exists');
check(mapCode.includes("onPick(String(match.id))"),'Real optical event ID is routed from map selection');
check(mapCode.includes("clusterRadius:42"),'Crowded real optical observations can expand clusters');
check(mapCode.includes("map.fitBounds(bounds"),'Map fits only with a button');
check(!mapCode.includes("map.flyTo({center:selection"),'Selecting a flash does not hijack map navigation');
check(mapCode.includes("['get','marker_radius_px']"),'Solar pixels are sized by source MW-derived marker metadata');
check(js.includes("void inspect()"),'Map tap initiates actual nearest-asset query');
check(html.includes('id="inspect" disabled'),'Cannot search without actual feed');
check(html.includes('id="flash" disabled'),'No fabricated default optical event');
check(html.includes('min-height:44px'),'Mobile touch-size declared on controls');
check(html.includes('not</strong> necessarily a ground strike'),'Observation disclaimer in initial static HTML');
check(js.includes('ventus-grid-engine@69b4e88c8464f0310bd67e47ec83ee8afa9e1921'),'Use immutable shared source, not a duplicate nearest engine');
check(js.includes('createLightningContextEngine'),'Import existing nearest engine');
check(js.includes("from './feed-contract.mjs'"),'Use separately testable optical feed provenance contract');
check(js.includes('describeOpticalFeedEvidence(parsed.evidence)'),'Expose latest query and UNKNOWN coverage to user');
check(js.includes("state.ctx=null;\n  mapView?.clearContext();\n  el('scenario').disabled=true;\n  clear('substations')"),'Refresh clears stale map proximity and disables stale scenarios');
check(js.includes('lightningElectricalScenario'),'Import existing scenario adapter');
check(js.includes('postEventDiligence'),'Reuse pure diligence contract from existing engine');
check(html.includes('id="safety-boundary"'),'Mandatory three-part evidence boundary visible without interaction');
check(html.includes('not evidence that any asset was hit'),'Optical is not necessarily ground strike');
check(html.includes('switching transients'),'Other fault causes explicit');
check(html.includes('diligence recommendation, not a diagnosis'),'Inspection not diagnosis');
check(html.includes('id="overhead"'),'Pylon proximity explicitly supplied by user');
check(html.includes('id="weather"'),'Moisture explicitly supplied by user');
check(js.includes('diligence.actions.forEach'),'Show checklist from shared engine, not duplicate logic');
check(js.includes('Parameters changed. Run proximity search again.'),'No stale map context after radius or voltage changes');
check(html.includes('string-inverters-wpx051-en.pdf'),'Cite owner-provided DEHN technical guidance');
check(js.includes('www.')===false || !js.includes('eval('),'No dynamic eval');
check(js.includes('https://raw.githubusercontent.com/Ventusltd/lightning/main/data/uk_lightning.geojson'),'Real live optical feed');
check(js.includes('Ventusltd/pipelinenews/main/data/atlas/'),'Genuine solar partitions');
check(js.includes('grid_substations.geojson'),'Actual original Atlas substation dataset');
check(js.includes('location.href'),'Deep-link selected genuine source event');
check(js.includes('flash_id'),'Unique real flash key, not fake REPD identity');
check(js.includes('Earlier than the seven-day feed remains UNKNOWN'),'Coverage honesty maintained');
check(js.includes("a.target='_blank'") && !js.includes('innerHTML='),'External links created by DOM properties without HTML injection');
check(js.includes("a.rel='noopener noreferrer'"),'External receiver links protect opener');
check(!/setLayoutProperty|addLayer|addSource|atlas\/current\.json.*write/.test(js),'Do not edit or reimplement original map shell');
check(!js.includes('calculateFaultCurrent('),'No fake quantitative protection calculations');
const compile=spawnSync(process.execPath,['--check',resolve(root,app)],{encoding:'utf8'});
check(compile.status===0,'ESM syntax parses: '+compile.stderr);
const bytes=new TextEncoder().encode(js).length;
check(bytes<30000,'Bounded standalone controller size');
console.log('PASS — '+count+' isolated Lightning → Grid Lab static checks; app '+bytes+' UTF-8 bytes.');
