import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {execFileSync} from 'node:child_process';
import {build, inputs, ROOT, G, PARENT, hash, SCRIPT_BUDGET, INPUT_BUDGET, TOTAL_BUDGET} from '../journey-context/build.mjs';
const frozen = '0cf8680d421f2cb659aa9924291c211466394490';
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8').replace(/\r\n/g, '\n');
const result = build(true), {pin, artifact} = inputs();
const current = JSON.parse(read(`atlas/v/${G}/current.json`)), parent = JSON.parse(read(`atlas/v/${PARENT}/current.json`));
assert.deepEqual(current.cartridges.slice(0, -1), parent.cartridges);
assert.deepEqual(current.cartridge_order.slice(0, -1), parent.cartridge_order);
const cartridge = current.cartridges.at(-1);
assert.equal(cartridge.id, 'grid-journey-official-context'); assert.equal(cartridge.after, 'grid-journey-preview');
assert.equal(hash(fs.readFileSync(path.join(ROOT, 'atlas', pin.artifact.previewPath))), pin.artifact.sha256);
assert.ok(result.scriptBytes <= SCRIPT_BUDGET && artifact.length <= INPUT_BUDGET && result.scriptBytes + artifact.length <= TOTAL_BUDGET);
const git = (...args) => execFileSync('git', args, {cwd: ROOT});
const frozenFiles = git('ls-tree', '-r', '--name-only', frozen, '--', 'tools/journey', 'atlas/v/202611171525', 'atlas/modules/202611171525-grid-journey-preview.js', 'atlas/manifests/202611171525-composition.json', 'tools/proofs/202611171525-grid-journey-preview.proof.mjs', 'atlas/current.json', 'atlas/index.html', 'STATE.md').toString('utf8').trim().split('\n');
for (const p of frozenFiles) assert.equal(read(p), git('show', `${frozen}:${p}`).toString('utf8').replace(/\r\n/g, '\n'), `Frozen GJ03/live file changed: ${p}`);
assert.equal(git('diff', frozen, '--name-only', '--', 'atlas/releases', 'atlas/cartridges').toString('utf8').trim(), '');
new vm.Script(read(`atlas/modules/${G}-grid-journey-official-context.js`));
console.log('GJ04 canonical producer pins, local asset budget, deterministic composition and frozen GJ03/live preservation PASS', result);
