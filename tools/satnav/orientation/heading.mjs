import { distanceKm, initialBearingDeg } from '../vendor/9698781539e549deaa6ecaa4a2b34610c1f9fd29/vendor/grid-distance-maths/src/geodesy.mjs';
import { MAX_ACCURACY_M } from '../vendor/9698781539e549deaa6ecaa4a2b34610c1f9fd29/nav/compass.mjs';

const radians = Math.PI / 180;
const normalise = degrees => (degrees % 360 + 360) % 360;

export function formatDegrees(degrees) {
  return String(Math.round(normalise(degrees)) % 360).padStart(3, '0') + '°';
}

// Project the screen's top edge onto the horizontal plane using the W3C
// intrinsic Z-X'-Y'' rotation. A vertical top edge has no horizontal heading.
export function deviceHeading(event, screenAngle = 0) {
  if (!Number.isFinite(screenAngle)) return null;
  const beta = (Number.isFinite(event.beta) ? event.beta : 0) * radians;
  const gamma = (Number.isFinite(event.gamma) ? event.gamma : 0) * radians;
  const angle = screenAngle * radians;
  const east = Math.cos(gamma) * Math.sin(angle);
  const north = Math.sin(beta) * Math.sin(gamma) * Math.sin(angle) + Math.cos(beta) * Math.cos(angle);
  if (Math.hypot(east, north) < 0.15) return null;
  const screenOffset = Math.atan2(east, north) / radians;

  if (typeof event.webkitCompassHeading === 'number') {
    const heading = event.webkitCompassHeading;
    const accuracy = event.webkitCompassAccuracy;
    if (!Number.isFinite(heading) || heading < 0 || heading > 360) return null;
    if (accuracy != null && (!Number.isFinite(accuracy) || accuracy < 0)) return null;
    // WebKit reports the magnetic bearing of the device's top in portrait.
    // The portrait edge points backwards if the phone is held upside down.
    const portraitOffset = Math.cos(beta) < 0 ? 180 : 0;
    return { degrees: normalise(heading + screenOffset - portraitOffset), reference: 'magnetic' };
  }
  if (!(event.absolute === true || event.type === 'deviceorientationabsolute')) return null;
  if (!Number.isFinite(event.alpha) || event.alpha < 0 || event.alpha > 360) return null;
  return { degrees: normalise(screenOffset - event.alpha), reference: 'sensor' };
}

// The V1 source contains the two manually selected endpoints, a measured
// marker and an accuracy circle generated by the same canonical maths. Read
// only those published roles; never open another location watch.
export function compactTargetBearing(features) {
  if (!Array.isArray(features)) return '';
  const roles = new Map(features.map(feature => [feature.properties?.role, feature.geometry]));
  const to = roles.get('destination-point')?.coordinates;
  const measured = roles.get('measured-gps')?.coordinates;
  const from = measured ?? roles.get('start-point')?.coordinates;
  if (!from || !to) return '';
  const distanceM = 1000 * distanceKm(...from, ...to);
  const edge = roles.get('gps-accuracy')?.coordinates?.[0]?.[0];
  const accuracyM = measured && edge ? 1000 * distanceKm(...measured, ...edge) : 0;
  if (measured && accuracyM > MAX_ACCURACY_M + 0.001) return 'Bearing awaiting an accurate GPS fix';
  if (measured && distanceM <= accuracyM + 0.001) return 'TO within GPS accuracy';
  if (distanceM < 0.001) return 'FROM and TO coincide';
  const deltaLon = normalise(to[0] - from[0]);
  if (Math.abs(deltaLon - 180) < 1e-9 && Math.abs(to[1] + from[1]) < 1e-9) return 'Bearing undetermined';
  return (measured ? 'GPS to TO ' : 'FROM to TO ') + formatDegrees(initialBearingDeg(...from, ...to)) + ' true';
}
